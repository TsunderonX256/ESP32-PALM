#pragma once

#define PALM_PROFILE_IIIX 1
#define PALM_PROFILE_M100_EXPERIMENTAL 2
#define PALM_PROFILE_IIIC_EXPERIMENTAL 3

#ifndef PALM_HARDWARE_PROFILE
#define PALM_HARDWARE_PROFILE PALM_PROFILE_IIIX
#endif

#define PALM_RAM_BASE 0x00000000UL
#define PALM_RAM_TOP_ALIAS_END 0x01000000UL
#define PALM_ROM_BASE 0x10c08000UL
#define PALM_ROM_LOW_ALIAS_BASE 0x10c00000UL
#define PALM_ROM_CHIP_SELECT_SIZE (16UL * 1024UL * 1024UL)
#define PALM_ENABLE_24BIT_ALIASES 1
#define PALM_LCD_W 160
#define PALM_LCD_H 160
#define PALM_SILKSCREEN_H 60

#if PALM_HARDWARE_PROFILE == PALM_PROFILE_IIIX
#define PALM_PROFILE_NAME "Palm IIIx"
#define PALM_RAM_LOGICAL_SIZE (4UL * 1024UL * 1024UL)
#define PALM_HAS_SED1375 0
#define PALM_SYSTEM_CLOCK_HZ 16000000.0

#elif PALM_HARDWARE_PROFILE == PALM_PROFILE_M100_EXPERIMENTAL
#define PALM_PROFILE_NAME "Palm m100 experimental"
#define PALM_RAM_LOGICAL_SIZE (2UL * 1024UL * 1024UL)
#define PALM_HAS_SED1375 0
#define PALM_SYSTEM_CLOCK_HZ 16000000.0

#elif PALM_HARDWARE_PROFILE == PALM_PROFILE_IIIC_EXPERIMENTAL
// Desktop profile parity only. The ESP32/CYD path does not currently emulate
// the IIIc's external SED1375 color LCD controller.
#define PALM_PROFILE_NAME "Palm IIIc experimental"
#define PALM_RAM_LOGICAL_SIZE (8UL * 1024UL * 1024UL)
#define PALM_HAS_SED1375 1
#define PALM_SED1375_BASE 0x1f000000UL
#define PALM_SED1375_REG_BASE 0x1f01ffe0UL
#define PALM_SED1375_REG_SIZE 0x20UL
#define PALM_SED1375_VRAM_SIZE (80UL * 1024UL)
#define PALM_SYSTEM_CLOCK_HZ 20000000.0

#else
#error Unsupported PALM_HARDWARE_PROFILE
#endif

#define PALM_ROM_LOW_24BIT_ALIAS_BASE (PALM_ROM_LOW_ALIAS_BASE & 0x00ffffffUL)
#define PALM_ROM_24BIT_BASE (PALM_ROM_BASE & 0x00ffffffUL)
#define PALM_DIGITIZER_W PALM_LCD_W
#define PALM_DIGITIZER_H (PALM_LCD_H + PALM_SILKSCREEN_H)
#define PALM_LCD_BYTES ((PALM_LCD_W * PALM_LCD_H) / 8)
